def parse_russian_number_sequence(words: list[str]) -> tuple[int, int] | None:
    """Parse a sequence of Russian number words from the start of `words`.

    Returns (value, count_of_words_consumed) or None.
    """
    if not words:
        return None
    w0 = words[0].lower().replace("ё", "е")
    # Don't convert a single 'один', 'одна', 'одно' unless followed by another number word,
    # as in Russian "один человек" / "однажды" is common.
    if len(words) == 1 and w0 in ("один", "одна", "одно"):
        return None

    total = 0
    current = 0
    consumed = 0

    for w in words:
        w_norm = w.lower().replace("ё", "е")
        val = None

        if w_norm in _ORDINALS:
            val = _ORDINALS[w_norm]
            current += val
            consumed += 1
            break  # Ordinal typically finishes the number phrase (e.g. "тысяча девятьсот сорок третий")
        elif w_norm in _ONES:
            val = _ONES[w_norm]
            current += val
            consumed += 1
        elif w_norm in _TEENS:
            val = _TEENS[w_norm]
            current += val
            consumed += 1
        elif w_norm in _TENS:
            val = _TENS[w_norm]
            current += val
            consumed += 1
        elif w_norm in _HUNDREDS:
            val = _HUNDREDS[w_norm]
            current += val
            consumed += 1
        elif w_norm in _THOUSANDS:
            mult = current if current > 0 else 1
            total += mult * 1000
            current = 0
            consumed += 1
        elif w_norm in _MILLIONS:
            mult = current if current > 0 else 1
            total += mult * 1000000
            current = 0
            consumed += 1
        else:
            break

    total += current
    if consumed > 0 and total > 0:
        return total, consumed
    return None


def numbers_to_digits_ru(text: str) -> str:
    """Convert Russian spoken numbers to digits:

    'тысяча девятьсот сорок третий год' -> '1943 год'
    'двадцать пять рублей' -> '25 рублей'
    'одиннадцать человек' -> '11 человек'
    """
    words = text.split()
    out = []
    i = 0
    while i < len(words):
        # Strip trailing punctuation for number detection
        cleaned = re.sub(r"[^\w-]", "", words[i].lower())
        match = parse_russian_number_sequence([re.sub(r"[^\w-]", "", w) for w in words[i:]])
        if match:
            val, count = match
            # Preserve punctuation from the last consumed word
            punct = re.search(r"[^\w-]+$", words[i + count - 1])
            p_str = punct.group(0) if punct else ""
            out.append(f"{val}{p_str}")
            i += count
        else:
            out.append(words[i])
            i += 1
    return " ".join(out)


