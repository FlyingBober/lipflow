# -----------------------------------------------------------------------------
# Visemes (lip shapes for Russian phonemes)
# -----------------------------------------------------------------------------
# M: bilabial closures (б, п, м) - lips completely closed
# F: labiodental fricatives (в, ф) - lower lip against upper teeth
# T: alveolar/dental stops & fricatives (д, т, з, с, ц, н) - tongue at teeth/alveolar ridge
# SH: postalveolar/palato-alveolar (ж, ш, ч, щ) - rounded, protruded lips ("трубочка"/"хоботок")
# K: velar consonants (г, к, х) - back of tongue, lips neutral
# R: liquids/trills (р, л) - tongue curled/alveolar
# A: open unrounded vowels (а, я) - wide mouth opening
# U: rounded/protruded vowels (о, у, ё, ю) - lips protruded or oval
# I: front unrounded vowels (и, е, э, ы) - lips spread wide in a smile
_VISEME_MAP = {
    # Bilabial
    "б": "M", "п": "M", "м": "M",
    # Labiodental
    "в": "F", "ф": "F",
    # Dental / alveolar
    "д": "T", "т": "T", "з": "T", "с": "T", "ц": "T", "н": "T",
    # Postalveolar / palato-alveolar
    "ж": "SH", "ш": "SH", "ч": "SH", "щ": "SH",
    # Velar
    "г": "K", "к": "K", "х": "K",
    # Liquids
    "р": "R", "л": "R",
    # Vowels
    "а": "A", "я": "A",
    "о": "U", "у": "U", "ё": "U", "ю": "U",
    "и": "I", "е": "I", "э": "I", "ы": "I",
    # Silent / neutral / reduction
    "й": "", "ь": "", "ъ": "",
}


def visemes(word: str) -> str:
    """Map a Russian word to a coarse viseme string (lip shape sequence)."""
    w = re.sub(r"[^а-яё]", "", word.lower())
    out = [_VISEME_MAP.get(ch, "") for ch in w]
    s = "".join(out)
    return re.sub(r"(.)\1+", r"\1", s)  # collapse duplicate adjacent visemes


